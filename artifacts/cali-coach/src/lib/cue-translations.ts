/**
 * Return a pre-translated main-workout coaching phrase for the given BCP-47 language.
 *
 * Keys are the English cue text verbatim (use the exact English string as the key).
 * For parameterised cues (containing `{n}`), call `.replace("{n}", value)` on the result.
 *
 * Falls back gracefully: target language → English entry → the englishCue itself.
 */
export function getWorkoutPhrase(englishCue: string, bcp47: string): string {
  const lang = (bcp47 ?? "en").split("-")[0]!.toLowerCase();
  return WORKOUT_CUES[englishCue]?.[lang] ?? WORKOUT_CUES[englishCue]?.["en"] ?? englishCue;
}
